# Data Types in Python

# Integer
age = 20
print("Integer:", age)
print(type(age))

# Float
cgpa = 8.71
print("\nFloat:", cgpa)
print(type(cgpa))

# String
name = "Prakhar Singh"
print("\nString:", name)
print(type(name))

# Boolean
is_student = True
print("\nBoolean:", is_student)
print(type(is_student))

# List
subjects = ["Python", "SQL", "Machine Learning"]
print("\nList:", subjects)
print(type(subjects))

# Tuple
coordinates = (10, 20)
print("\nTuple:", coordinates)
print(type(coordinates))

# Set
colors = {"Red", "Blue", "Green"}
print("\nSet:", colors)
print(type(colors))

# Dictionary
student = {
    "Name": "Prakhar Singh",
    "Age": 20,
    "CGPA": 8.71
}
print("\nDictionary:", student)
print(type(student))