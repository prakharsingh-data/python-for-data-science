# Variables in Python

# String variable
name = "Prakhar Singh"

# Integer variable
age = 20

# Float variable
cgpa = 8.71

# Boolean variable
is_student = True

print("Name:", name)
print("Age:", age)
print("CGPA:", cgpa)
print("Student:", is_student)

# Arithmetic example
a = 15
b = 10

print("\nArithmetic Operations")
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)